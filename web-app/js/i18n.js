// Current language (defaults to zh)
let _currentLang = localStorage.getItem('ob_lang') || 'zh';

function t(key) {
    // 用 `key in` 判定「键是否存在」，使空字符串('')也是有效翻译（不再回退到中文或键名）。
    const cur = LANGS[_currentLang];
    if (cur && key in cur) return cur[key];
    if (LANGS['zh'] && key in LANGS['zh']) return LANGS['zh'][key];
    return key;
}

function setLang(lang) {
    if (!LANGS[lang]) return;
    _currentLang = lang;
    localStorage.setItem('ob_lang', lang);
    applyI18n();
}

function getLang() { return _currentLang; }

function applyI18n() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const attr = el.dataset.i18nAttr; // optional: placeholder, title, etc.
        const val = t(key);
        if (attr) {
            el.setAttribute(attr, val);
            // 图标按钮(title)同时给无障碍名称：镜像为 aria-label 并随语言更新。
            // 仅处理「自动设置」的，绝不覆盖元素上手写的 aria-label。
            if (attr === 'title' && (!el.hasAttribute('aria-label') || el.dataset.i18nAriaAuto)) {
                el.setAttribute('aria-label', val);
                el.dataset.i18nAriaAuto = '1';
            }
        }
        else if (val.includes('<')) el.innerHTML = val;
        else el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        el.placeholder = t(el.dataset.i18nPh);
    });
    // Update preset question data-question attributes
    document.querySelectorAll('[data-i18n-question]').forEach(el => {
        const key = el.dataset.i18nQuestion;
        el.dataset.question = t(key);
    });
    // Update lang buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === _currentLang);
    });
    // Fire custom event so app.js can react
    document.dispatchEvent(new CustomEvent('langchange', { detail: _currentLang }));
}

// Auto-apply on load
document.addEventListener('DOMContentLoaded', applyI18n);
